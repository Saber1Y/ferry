#!/usr/bin/env bash
# Local regtest chain for FERRY: zebrad (Docker) + two lightwalletd on loopback.
#   A (sync)      127.0.0.1:9067
#   B (broadcast) 127.0.0.1:9077
#
# Usage:
#   chain.sh start [miner_address]   start (or restart) zebrad mining to that address, then both lightwalletd
#   chain.sh mine <n>                mine n blocks
#   chain.sh height                  print the chain height
#   chain.sh rpc <method> [json]     raw JSON-RPC call to zebrad
#   chain.sh stop                    stop everything
#   chain.sh reset                   stop and delete all chain state
#
# Env: LIGHTWALLETD (binary, default ../.deps/bin/lightwalletd), ZEBRA_IMAGE.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=heights.env
source "$HERE/heights.env"
CHAIN="$HERE/chain"
ZEBRA_IMAGE="${ZEBRA_IMAGE:-zfnd/zebra:7.0.0-rc.0}"
LWD="${LIGHTWALLETD:-$HERE/../.deps/bin/lightwalletd}"
CONTAINER=ferry-zebrad
RPC_PORT=18232
LWD_A=9067
LWD_B=9077

rpc() {
  curl -s --max-time 300 -H 'content-type: application/json' \
    --data-binary "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"$1\",\"params\":${2:-[]}}" \
    "http://127.0.0.1:$RPC_PORT/"
}
height() { rpc getblockcount | sed -n 's/.*"result":\([0-9]*\).*/\1/p'; }

render_configs() {
  mkdir -p "$CHAIN"
  local h=$EARLY_UPGRADES_HEIGHT
  cat > "$HERE/activation-heights.toml" <<TOML
# Generated by chain.sh from heights.env. Used by: zcash-devtool wallet init --activation-heights
overwinter = $h
sapling = $h
blossom = $h
heartwood = $h
canopy = $h
nu5 = $h
nu6 = $h
nu6_1 = $h
nu6_2 = $h
nu6_3 = $NU6_3_HEIGHT
nu7 = "never"
TOML
  {
    if [ -n "${1:-}" ]; then printf '[mining]\nminer_address = "%s"\n\n' "$1"; fi
    cat <<TOML
[network]
network = "Regtest"
listen_addr = "127.0.0.1:18233"
cache_dir = false

[network.testnet_parameters.activation_heights]
Overwinter = $h
Sapling = $h
Blossom = $h
Heartwood = $h
Canopy = $h
NU5 = $h
NU6 = $h
"NU6.1" = $h
"NU6.2" = $h
"NU6.3" = $NU6_3_HEIGHT

[rpc]
listen_addr = "0.0.0.0:$RPC_PORT"
enable_cookie_auth = false

[state]
cache_dir = "/state"

[tracing]
use_color = false
TOML
  } > "$CHAIN/zebrad.toml"
}

start_lwd() {
  for spec in "a:$LWD_A" "b:$LWD_B"; do
    name="${spec%%:*}"; port="${spec##*:}"
    pidfile="$CHAIN/lwd-$name.pid"
    if [ -f "$pidfile" ] && kill -0 "$(cat "$pidfile")" 2>/dev/null; then continue; fi
    mkdir -p "$CHAIN/lwd-$name"
    "$LWD" --no-tls-very-insecure \
      --grpc-bind-addr "127.0.0.1:$port" --http-bind-addr "127.0.0.1:$((port + 1))" \
      --rpchost 127.0.0.1 --rpcport "$RPC_PORT" --rpcuser x --rpcpassword x \
      --data-dir "$CHAIN/lwd-$name" --log-file "$CHAIN/lwd-$name.log" \
      < /dev/null >> "$CHAIN/lwd-$name.out" 2>&1 &
    echo $! > "$pidfile"
  done
}

stop_lwd() {
  for name in a b; do
    pidfile="$CHAIN/lwd-$name.pid"
    if [ -f "$pidfile" ]; then kill "$(cat "$pidfile")" 2>/dev/null || true; rm -f "$pidfile"; fi
  done
}

case "${1:-}" in
  start)
    render_configs "${2:-}"
    # zebrad writes its newest (non-finalized) blocks to disk only every few seconds. Stopping it
    # right after mining silently rolls those blocks back, and they get re-mined to whatever
    # address the next start uses. Wait for the backup, then stop it gracefully.
    if docker ps -q -f "name=^${CONTAINER}$" | grep -q .; then
      sleep 6
      docker stop -t 30 "$CONTAINER" > /dev/null 2>&1 || true
    fi
    docker rm -f "$CONTAINER" > /dev/null 2>&1 || true
    mkdir -p "$CHAIN/state"
    docker run -d --name "$CONTAINER" \
      -p "127.0.0.1:$RPC_PORT:$RPC_PORT" \
      -v "$CHAIN/zebrad.toml:/etc/zebrad/zebrad.toml:ro" \
      -v "$CHAIN/state:/state" \
      "$ZEBRA_IMAGE" zebrad -c /etc/zebrad/zebrad.toml start > /dev/null
    for _ in $(seq 1 60); do
      if rpc getblockcount | grep -q '"result"'; then break; fi
      sleep 1
    done
    rpc getblockcount | grep -q '"result"' || { echo "zebrad did not answer; docker logs $CONTAINER" >&2; exit 1; }
    stop_lwd
    start_lwd
    echo "zebrad up at height $(height); lightwalletd A :$LWD_A (sync), B :$LWD_B (broadcast)"
    ;;
  mine)
    n="${2:?usage: chain.sh mine <n>}"
    while [ "$n" -gt 0 ]; do
      step=$(( n > 20 ? 20 : n ))
      out=$(rpc generate "[$step]")
      echo "$out" | grep -q '"error"' && { echo "$out" >&2; exit 1; }
      n=$(( n - step ))
    done
    echo "height $(height)"
    ;;
  height) echo "$(height)" ;;
  rpc) rpc "${2:?method}" "${3:-[]}"; echo ;;
  stop)
    stop_lwd
    docker rm -f "$CONTAINER" > /dev/null 2>&1 || true
    echo "stopped"
    ;;
  reset)
    "$0" stop
    rm -rf "$CHAIN"
    echo "chain state deleted"
    ;;
  *) sed -n '2,16p' "$0"; exit 2 ;;
esac
